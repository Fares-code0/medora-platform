import { isValidColor } from './color';
import {
  COPIED_TOKEN_NAMES,
  COPIED_TOKENS,
  LEGACY_FILLS,
  META_BY_TOKEN,
  TOKEN_META,
  WEB_TOKENS,
  cssVar,
  type Palette,
  type WebToken,
} from './tokens';

/**
 * Theme exports. Each format carries EVERY token of its target, never a
 * sample: an export that silently omitted `--color-chart-4-edge` would paste
 * into tokens.css and leave the old value behind with no error.
 *
 * - CSS   → the two token blocks of `frontend/src/styles/tokens.css`, copies
 *           written as the references tokens.css declares (`:root` only).
 * - TS    → `lightColors` / `darkColors` of `patient-app/src/theme/tokens.ts`.
 * - JSON  → the interchange format both playgrounds can load.
 */

export interface ThemeExport {
  readonly name: string;
  readonly light: Palette;
  readonly dark: Palette;
}

/** `medora-theme@1` — the JSON both playgrounds read and write. */
export const JSON_FORMAT = 'medora-theme@1';

function cssBlock(selector: string, palette: Palette, withCopies: boolean): string {
  const lines = WEB_TOKENS.map((token) => `  ${cssVar(token)}: ${palette[token]};`);
  // A copy is declared once, on `:root`, as a reference — exactly as in
  // tokens.css — so it follows its source in both modes and cannot drift.
  if (withCopies) {
    for (const name of COPIED_TOKEN_NAMES) lines.push(`  ${name}: var(${COPIED_TOKENS[name].source});`);
  }
  return `${selector} {\n${lines.join('\n')}\n}`;
}

export function toCss({ name, light, dark }: ThemeExport): string {
  return [
    `/* Medora theme — ${name}`,
    '   Generated by the Theme Playground. Paste each value over the same',
    '   variable in frontend/src/styles/tokens.css (`:root` = light, `.dark` = dark). */',
    cssBlock(':root', light, true),
    '',
    cssBlock('.dark', dark, false),
    '',
  ].join('\n');
}

/**
 * Every `ColorPalette` key and the token whose value it takes. A copy keeps
 * its patient key (the patient app still has `secondary`) and takes its
 * source's value — which is what the copy resolves to on the web.
 */
export const PATIENT_KEYS: readonly { readonly key: string; readonly token: WebToken }[] = [
  ...TOKEN_META.flatMap((m) => (m.patient === null ? [] : [{ key: m.patient, token: m.name }])),
  ...COPIED_TOKEN_NAMES.flatMap((name) => {
    const copy: { readonly source: WebToken; readonly patient: string | null } = COPIED_TOKENS[name];
    return copy.patient === null ? [] : [{ key: copy.patient, token: copy.source }];
  }),
];

const WEB_ONLY: readonly string[] = [
  ...TOKEN_META.filter((m) => m.patient === null).map((m) => cssVar(m.name)),
  ...COPIED_TOKEN_NAMES.filter((name) => COPIED_TOKENS[name].patient === null),
];

function tsObject(constName: string, palette: Palette): string {
  const lines = PATIENT_KEYS.map(({ key, token }) => `  ${key}: '${palette[token]}',`);
  return `export const ${constName}: ColorPalette = {\n${lines.join('\n')}\n};`;
}

export function toTypeScript({ name, light, dark }: ThemeExport): string {
  return [
    `/* Medora theme — ${name}`,
    '   Generated by the Theme Playground. Replace the two objects of the same',
    '   name in patient-app/src/theme/tokens.ts.',
    `   Web-only roles, not part of ColorPalette: ${WEB_ONLY.join(', ')}. */`,
    "import type { ColorPalette } from './tokens';",
    '',
    tsObject('lightColors', light),
    '',
    tsObject('darkColors', dark),
    '',
  ].join('\n');
}

/** Always the CURRENT catalogue: every editable token, no copies, no legacy keys. */
export function toJson({ name, light, dark }: ThemeExport): string {
  return `${JSON.stringify({ format: JSON_FORMAT, name, light, dark }, null, 2)}\n`;
}

export type ParseResult =
  | {
      readonly ok: true;
      readonly theme: ThemeExport;
      /** What was migrated from an older catalogue — present only when something was. */
      readonly notes?: readonly string[];
    }
  | { readonly ok: false; readonly error: string };

/** The shipped palettes, for the roles a legacy document predates entirely. */
export interface LegacyOriginal {
  readonly light: Palette;
  readonly dark: Palette;
}

const labelOf = (token: string): string =>
  token in META_BY_TOKEN ? META_BY_TOKEN[token as WebToken].label : token;

/**
 * Reads a `medora-theme@1` JSON document back. Every token must be present and
 * valid — except the ones an earlier catalogue did not have (`LEGACY_FILLS`),
 * which are filled deterministically and reported in `notes`:
 *
 * - a role split out of another takes that token's saved value, so the
 *   experiment looks as it did when it was saved;
 * - a role that did not exist takes the shipped value from `original`
 *   (without it, such a document is refused, not guessed at);
 * - a saved value for a token that is now a COPY is superseded by its source
 *   — noted whenever the two differed, so nothing is dropped unannounced;
 * - any other key the catalogue does not know is ignored, and noted.
 */
export function parseThemeJson(text: string, original?: LegacyOriginal): ParseResult {
  let data: unknown;
  try {
    data = JSON.parse(text);
  } catch {
    return { ok: false, error: 'Not valid JSON.' };
  }
  if (typeof data !== 'object' || data === null) return { ok: false, error: 'Expected an object.' };
  const record = data as Record<string, unknown>;
  if (record['format'] !== JSON_FORMAT) {
    return { ok: false, error: `Expected "format": "${JSON_FORMAT}".` };
  }

  const filled = new Set<string>();
  const notes: string[] = [];

  const readMode = (mode: 'light' | 'dark'): Palette | string => {
    const source = record[mode];
    if (typeof source !== 'object' || source === null) return `Missing "${mode}" palette.`;
    const values = source as Record<string, unknown>;
    const out = {} as Record<WebToken, string>;
    const valid = (value: unknown): value is string => typeof value === 'string' && isValidColor(value);

    for (const token of WEB_TOKENS) {
      const value = values[token];
      if (valid(value)) {
        out[token] = value;
        continue;
      }
      const fill = value === undefined ? LEGACY_FILLS[token] : undefined;
      if (fill !== undefined && 'from' in fill && valid(values[fill.from])) {
        out[token] = values[fill.from] as string;
        filled.add(`${META_BY_TOKEN[token].label} (from ${META_BY_TOKEN[fill.from].label})`);
        continue;
      }
      if (fill !== undefined && 'original' in fill && original !== undefined) {
        out[token] = original[mode][token];
        filled.add(`${META_BY_TOKEN[token].label} (shipped value)`);
        continue;
      }
      return `"${mode}.${token}" (${META_BY_TOKEN[token].label}) is missing or not a colour.`;
    }

    for (const [key, value] of Object.entries(values)) {
      if (key in META_BY_TOKEN) continue;
      if (key in COPIED_TOKENS) {
        const copy = COPIED_TOKENS[key as keyof typeof COPIED_TOKENS];
        if (typeof value === 'string' && value.toLowerCase() !== out[copy.source].toLowerCase()) {
          notes.push(
            `${mode}: ${copy.label} (${value}) now follows ${labelOf(copy.source)} (${out[copy.source]}) — it is a copy, not an editable role.`,
          );
        }
        continue;
      }
      notes.push(`${mode}: ignored "${key}", which is not a Medora colour token.`);
    }
    return out;
  };

  const light = readMode('light');
  if (typeof light === 'string') return { ok: false, error: light };
  const dark = readMode('dark');
  if (typeof dark === 'string') return { ok: false, error: dark };
  if (filled.size > 0) {
    notes.unshift(`Added roles this theme predates: ${[...filled].join(', ')}.`);
  }
  const name = typeof record['name'] === 'string' ? record['name'] : 'Imported theme';
  const theme: ThemeExport = { name, light, dark };
  return notes.length > 0 ? { ok: true, theme, notes } : { ok: true, theme };
}
