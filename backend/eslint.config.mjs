// ESLint 9 flat config — mirrors the frontend's discipline (RM M1.1),
// plus the module boundary rules of RM M2.2.
import js from '@eslint/js';
import importPlugin from 'eslint-plugin-import';
import tseslint from 'typescript-eslint';

/**
 * The nineteen domain modules of RM M2.1, in the roadmap's order.
 * Adding a module means adding it here — the zones below are generated
 * from this list, so a module left out simply has no boundary.
 */
const DOMAIN_MODULES = [
  'auth',
  'users',
  'doctors',
  'patients',
  'appointments',
  'medical-records',
  'labs',
  'pharmacy',
  'messaging',
  'notifications',
  'ai',
  'reports',
  'settings',
  'administration',
  'platform-settings',
  'audit',
  'files',
  'search',
  'dashboard',
  // M1 infrastructure; it lives under `modules/` and obeys the same rule.
  'health',
];

/** The only files inside `src/shared/` a domain module may import. */
const SHARED_PUBLIC_API = [
  './index.ts',
  './activity/index.ts',
  './ai/index.ts',
  './audit/index.ts',
  './authz/index.ts',
  './cache/index.ts',
  './crypto/index.ts',
  './database/index.ts',
  './outbox/index.ts',
  './files/index.ts',
  './idempotency/index.ts',
  './jobs/index.ts',
  './mail/index.ts',
  './metrics/index.ts',
  './phi/index.ts',
  './platform-policy/index.ts',
  './push/index.ts',
  './rate-limit/index.ts',
  './status/index.ts',
];

/**
 * Zone 1 — a module may not reach into a sibling.
 *
 * The frontend's feature isolation is the model: `features/labs` cannot
 * import `features/pharmacy`, and the backend mirrors it. A module that
 * needs another module's data queries it through its own repository or
 * publishes to `shared/outbox`; a module that needs another module's
 * *behaviour* is a design that should have been one module.
 *
 * `except` is relative to `from`, so each zone allows exactly the
 * module's own folder back in.
 */
const siblingZones = DOMAIN_MODULES.map((module) => ({
  target: `./src/modules/${module}`,
  from: './src/modules',
  except: [`./${module}`],
  message: `Modules are isolated (RM M2.2). Reach a sibling through shared/outbox or your own repository, not by importing it.`,
}));

export default tseslint.config(
  {
    // This config file is not part of the TS project, so type-aware
    // linting cannot resolve it.
    //
    // The boundary fixtures are ignored here and linted deliberately by
    // `test/boundaries.e2e-spec.ts`, which asserts that each one is
    // rejected. They exist to fail — a normal `eslint .` must not.
    ignores: [
      'dist/**',
      'node_modules/**',
      'coverage/**',
      'eslint.config.mjs',
      'src/**/__boundary-fixtures__/**',
      // Generated by `prisma generate` — not ours to lint, and it is
      // gitignored, so linting it would fail on a fresh clone anyway.
      'src/generated/**',
      // A k6 script: it runs in k6's JavaScript runtime (imports `k6/http`),
      // not Node, and is outside the TypeScript project the typed rules need.
      // `k6 run` is what parses it — locally and in perf-nightly.yml.
      'perf/k6/**',
    ],
  },
  js.configs.recommended,
  ...tseslint.configs.recommendedTypeChecked,
  {
    languageOptions: {
      parserOptions: {
        project: ['./tsconfig.json'],
        tsconfigRootDir: import.meta.dirname,
      },
    },
    rules: {
      // Nest controllers and providers are classes whose methods are
      // invoked by the framework; requiring `this` usage is noise here.
      'class-methods-use-this': 'off',

      // Surfaces accidental `any` leaking out of untyped libraries.
      '@typescript-eslint/no-explicit-any': 'error',
      '@typescript-eslint/no-unused-vars': [
        'error',
        { argsIgnorePattern: '^_', varsIgnorePattern: '^_' },
      ],

      // A floating promise in a request handler is a silently dropped
      // error — in this domain that can mean a lost clinical write.
      '@typescript-eslint/no-floating-promises': 'error',
      '@typescript-eslint/no-misused-promises': 'error',
    },
  },
  {
    // RM M2.2 — architectural boundaries, enforced by lint rather than
    // by review. These are the rules that keep nineteen modules from
    // becoming one; they are worth more the later they are added, and
    // cost the most then too, so they land before the first module has
    // a line of logic in it.
    files: ['src/**/*.ts'],
    plugins: { import: importPlugin },
    settings: {
      // Without a TS-aware resolver the rule cannot resolve `.ts`
      // imports or the `@/*` alias, and it skips what it cannot
      // resolve — which would make the whole zone list silently inert.
      'import/resolver': {
        typescript: { project: './tsconfig.json' },
      },
    },
    rules: {
      'import/no-restricted-paths': [
        'error',
        {
          zones: [
            ...siblingZones,

            // Zone 2 — `shared/` is reachable only through its public
            // API. Importing a kernel's internals would defeat the
            // point of the token indirection: M25 and M28 replace those
            // implementations, and nothing outside may depend on them.
            {
              target: './src/modules',
              from: './src/shared',
              except: SHARED_PUBLIC_API,
              message:
                'Import the shared kernel through its index (shared/activity, shared/ai, shared/audit, shared/authz, shared/cache, shared/crypto, shared/database, shared/idempotency, shared/jobs, shared/outbox, shared/files, shared/mail, shared/metrics, shared/phi, shared/push, shared/rate-limit, shared/status), not its internals (RM M2.3).',
            },

            // Zone 3 — the kernel does not depend on its callers.
            // `shared/` importing a module would create the cycle the
            // kernel exists to break.
            {
              target: './src/shared',
              from: './src/modules',
              message: 'The shared kernel must not depend on a domain module (RM M2.3).',
            },

            // Zone 4 — `common/` is the bottom of the stack. It is
            // imported by everything and imports nothing of ours.
            {
              target: './src/common',
              from: ['./src/modules', './src/shared', './src/config'],
              message:
                'common/ is the lowest layer; it cannot import modules, the shared kernel, or config.',
            },

            // Zone 5 — `config/` is reachable only through its index
            // (RM M3.1). `config/env.ts` is the only code that touches
            // `process.env`; a module able to import it could read a raw
            // secret straight out of the environment, bypassing the
            // typed accessors that exist precisely to stop that.
            {
              target: './src/modules',
              from: './src/config',
              except: ['./index.ts'],
              message:
                'Import configuration through its index (ConfigService, PolicyService), never config/env directly (RM M3.1).',
            },

            // Zone 6 — configuration does not depend on the things it
            // configures.
            {
              target: './src/config',
              from: ['./src/modules', './src/shared'],
              message: 'config/ must not depend on a domain module or the shared kernel (RM M3).',
            },
          ],
        },
      ],
    },
  },
  {
    // Decorator metadata means Nest DI reads types the linter cannot see.
    files: ['**/*.spec.ts', 'test/**/*.ts'],
    rules: {
      '@typescript-eslint/unbound-method': 'off',
    },
  },
);
